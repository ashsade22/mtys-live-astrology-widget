export function buildReading(first, second) {
  const order = signs.map((sign) => sign.key);
  const [one, two] = [first, second].sort((a, b) => order.indexOf(a.key) - order.indexOf(b.key));
  const pairKey = `${one.key}|${two.key}`;
  const override = pairOverrides[pairKey];
  if (override) {
    return override;
  }

  const oneProfile = profiles[one.key];
  const twoProfile = profiles[two.key];
  if (one.key === two.key) {
    return {
      overview: `${one.name} and ${two.name} may recognize the same instincts in each other quickly. You can understand the pace and the priorities without much explanation, but the similarities can also make the same blind spot louder.`,
      natural: `Both people bring ${oneProfile.gift}. There is comfort in not having to translate every reaction, especially when the two of you want the same thing.`,
      miss: `Both people can ${oneProfile.miss}. Because the response feels natural on both sides, it may take longer to notice that neither person is changing the pattern.`,
      tense: `When pressure rises, the same pattern can appear on both sides. Each person ${oneProfile.tension}. The reaction can keep repeating because each person understands it from the inside but feels it differently when receiving it.`,
      helps: `${oneProfile.help} Make room for one person to try a different response first instead of waiting for the other to change the tone.`
    };
  }

  const elementKey = [one.element, two.element].sort().join("|");
  const naturalLead = naturalConnections[elementKey];
  return {
    overview: `${one.name} often ${oneProfile.approach}. ${two.name} usually ${twoProfile.approach}. The relationship becomes easier to understand when those differences are treated as information instead of proof that one person cares more.`,
    natural: `${naturalLead} ${one.name} brings ${oneProfile.gift}. ${two.name} brings ${twoProfile.gift}.`,
    miss: `${one.name} may ${oneProfile.miss}. ${two.name} may ${twoProfile.miss}. The same moment can look completely different from each side, especially when nobody checks what the other person meant.`,
    tense: `${one.name} often ${oneProfile.tension}. ${two.name} often ${twoProfile.tension}. The issue gets harder when each person responds to the reaction instead of the need underneath it.`,
    helps: `${oneProfile.help} ${twoProfile.help} Do not expect the other person to process the moment at exactly the same pace.`
  };
}
